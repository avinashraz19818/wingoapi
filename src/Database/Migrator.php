<?php

declare(strict_types=1);

namespace Lottery\Database;

use Lottery\Support\Clock;
use Lottery\Support\Log;
use PDOException;
use Throwable;

/**
 * Versioned schema migrator.
 *
 * The bootstrap calls {@see migrate()} on the first request (and after every
 * deploy); pending versions are applied in order and recorded in
 * lot_migrations. Migrations are written once with portability placeholders so
 * the identical schema runs on MySQL 8+ (production) and SQLite (dev/tests).
 */
class Migrator
{
    private Connection $db;

    public function __construct(Connection $db)
    {
        $this->db = $db;
    }

    /** Highest known schema version. */
    public function latestVersion(): int
    {
        return max(array_keys($this->migrations()));
    }

    public function currentVersion(): int
    {
        $this->ensureMigrationsTable();
        return (int) ($this->db->fetchValue('SELECT COALESCE(MAX(version), 0) FROM ' . Tables::MIGRATIONS) ?? 0);
    }

    /**
     * Apply every pending migration.
     *
     * @return array<int,int> versions applied during this call
     */
    public function migrate(): array
    {
        $this->ensureMigrationsTable();
        $current = $this->currentVersion();
        $applied = [];

        foreach ($this->migrations() as $version => $statements) {
            if ($version <= $current) {
                continue;
            }
            foreach ($statements as $sql) {
                $this->exec($this->translate($sql));
            }
            $this->db->execute(
                'INSERT INTO ' . Tables::MIGRATIONS . ' (version, applied_at) VALUES (?, ?)',
                [$version, Clock::dateTime()]
            );
            $applied[] = $version;
            Log::info('schema migration applied', ['version' => $version]);
        }

        if ($applied !== []) {
            $this->seed();
        }

        return $applied;
    }

    /** Idempotent reference data (games + default follow plans). */
    public function seed(): void
    {
        (new Seeder($this->db))->run();
    }

    private function ensureMigrationsTable(): void
    {
        $this->exec($this->translate(
            'CREATE TABLE IF NOT EXISTS ' . Tables::MIGRATIONS . ' (
                version {INT} NOT NULL PRIMARY KEY,
                applied_at {DATETIME} NOT NULL
            ){ENGINE}'
        ));
    }

    private function exec(string $sql): void
    {
        try {
            $this->db->pdo()->exec($sql);
        } catch (PDOException $e) {
            // "duplicate index/column" is benign when re-running a migration
            // against a partially-migrated legacy database.
            $message = strtolower($e->getMessage());
            if (str_contains($message, 'duplicate') || str_contains($message, 'already exists')) {
                return;
            }
            throw $e;
        }
    }

    /**
     * Full DDL for one driver — used by tools/dump_schema.php to keep
     * schema.sql in sync with the migrations.
     */
    public function schemaSql(bool $mysql = true): string
    {
        $out = ["-- Generated by tools/dump_schema.php — do not edit by hand.",
                '-- Schema version: ' . $this->latestVersion(), ''];

        foreach ($this->migrations() as $version => $statements) {
            $out[] = "-- ---------------------------------------------------------------";
            $out[] = "-- Migration {$version}";
            $out[] = "-- ---------------------------------------------------------------";
            foreach ($statements as $sql) {
                $statement = (string) preg_replace('/\n\s+/', "\n    ", $this->translate($sql, $mysql));
                $out[] = rtrim($statement) . ';';
                $out[] = '';
            }
        }

        return implode(PHP_EOL, $out) . PHP_EOL;
    }

    /** Replace portability placeholders with driver-specific SQL. */
    private function translate(string $sql, ?bool $forceMysql = null): string
    {
        $mysql = $forceMysql ?? $this->db->isMysql();

        $map = $mysql ? [
            '{PK}'       => 'BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY',
            '{BIGINT}'   => 'BIGINT UNSIGNED',
            '{INT}'      => 'INT',
            '{TINYINT}'  => 'TINYINT',
            '{MONEY}'    => 'DECIMAL(18,2)',
            '{RATE}'     => 'DECIMAL(10,4)',
            // LONGTEXT rather than JSON: MariaDB and MySQL 5.6 do not have a
            // native JSON type, and nothing here queries inside the document.
            '{JSON}'     => 'LONGTEXT',
            '{TEXT}'     => 'TEXT',
            '{DATETIME}' => 'DATETIME',
            '{NOW}'      => 'CURRENT_TIMESTAMP',
            '{ENGINE}'   => ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci',
        ] : [
            '{PK}'       => 'INTEGER PRIMARY KEY AUTOINCREMENT',
            '{BIGINT}'   => 'INTEGER',
            '{INT}'      => 'INTEGER',
            '{TINYINT}'  => 'INTEGER',
            '{MONEY}'    => 'NUMERIC(18,2)',
            '{RATE}'     => 'NUMERIC(10,4)',
            '{JSON}'     => 'TEXT',
            '{TEXT}'     => 'TEXT',
            '{DATETIME}' => 'DATETIME',
            '{NOW}'      => 'CURRENT_TIMESTAMP',
            '{ENGINE}'   => '',
        ];

        return strtr($sql, $map);
    }

