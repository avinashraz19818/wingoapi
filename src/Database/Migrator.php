    /**
     * Best-effort bootstrap used by the HTTP kernel: never let a migration
     * failure take the whole API down when the schema is already current.
     */
    public function bootstrap(): void
    {
        try {
            if ($this->currentVersion() < $this->latestVersion()) {
                $this->migrate();
            }
        } catch (Throwable $e) {
            Log::exception($e, ['stage' => 'bootstrap-migrate']);
            throw $e;
        }
    }
